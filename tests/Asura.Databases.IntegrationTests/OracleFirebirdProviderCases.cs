internal static class OracleFirebirdProviderCases
{
    private const string Password = "Asura_Test1!";

    public static DatabaseProviderCase Oracle { get; } = new ContainerDatabaseProviderCase(
        "oracle",
        "Oracle Database Free 23.26.2",
        "container-registry.oracle.com/database/free:23.26.2.0-lite",
        1521,
        new Dictionary<string, string>(StringComparer.Ordinal)
