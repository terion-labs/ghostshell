    private static DatabaseSeed CreateFirebirdSeed() => new(
        [
            """
            CREATE FUNCTION "viewer_identity"("value" BIGINT)
            RETURNS BIGINT
            AS
            BEGIN
                RETURN "value";
            END
            """,
            """
            CREATE TABLE "viewer_rows" (
                "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "code" VARCHAR(80) NOT NULL UNIQUE,
                "title" VARCHAR(200) NOT NULL,
                "score" DECIMAL(12, 2) NOT NULL,
                "enabled" BOOLEAN NOT NULL,
                "note" VARCHAR(1000),
                "status" VARCHAR(40) DEFAULT 'draft' NOT NULL,
                "created_at" TIMESTAMP DEFAULT TIMESTAMP '2025-01-01 00:00:00' NOT NULL,
                "payload" VARCHAR(1000) DEFAULT '{}' NOT NULL,
                "blob_value" BLOB SUB_TYPE BINARY,
                "computed_label" VARCHAR(281)
                    COMPUTED BY ("title" || ':' || "code")
            )
            """,
            "CREATE DESCENDING INDEX \"idx_viewer_rows_score\" ON \"viewer_rows\" (\"score\", \"title\")",
            """
            INSERT INTO "viewer_rows"
                ("code", "title", "score", "enabled", "note", "status", "created_at", "payload", "blob_value")
            VALUES
                ('alpha', 'Alpha', -100.00, TRUE, 'one', DEFAULT,
                 TIMESTAMP '2025-01-01 00:00:00', '{"slot":1}', X'0102')
            """,
            """
            INSERT INTO "viewer_rows"
                ("code", "title", "score", "enabled", "note", "status", "created_at", "payload", "blob_value")
            VALUES
                ('beta', 'Beta', 0.00, FALSE, 'Robert''); DROP TABLE viewer_rows;--', 'published',
                 TIMESTAMP '2025-01-02 00:00:00', '{"slot":2}', NULL)
            """,
            """
            INSERT INTO "viewer_rows"
                ("code", "title", "score", "enabled", "note", "created_at", "payload")
            VALUES
                ('literal', 'literal%_!needle', 100.00, TRUE, NULL,
                 TIMESTAMP '2025-01-03 00:00:00', '{"slot":3}')
            """,
            """
            INSERT INTO "viewer_rows"
                ("code", "title", "score", "enabled", "note", "created_at", "payload")
            VALUES
                ('omega-a', 'Omega', 300.00, TRUE, 'four',
                 TIMESTAMP '2025-01-04 00:00:00', '{"slot":4}')
            """,
            """
            INSERT INTO "viewer_rows"
                ("code", "title", "score", "enabled", "note", "created_at", "payload")
            VALUES
                ('omega-b', 'unicode-🧪', 300.00, FALSE, 'comma,"quote"',
                 TIMESTAMP '2025-01-05 00:00:00', '{"slot":5}')
            """,
            """
            EXECUTE BLOCK AS
                DECLARE row_value INTEGER = 6;
            BEGIN
                WHILE (row_value <= 205) DO
                BEGIN
                    INSERT INTO "viewer_rows"
                        ("code", "title", "score", "enabled", "note")
                    VALUES
                        ('row-' || LPAD(CAST(:row_value AS VARCHAR(3)), 3, '0'),
                         'Row ' || CAST(:row_value AS VARCHAR(10)),
                         1000 + :row_value,
                         MOD(:row_value, 2) = 0,
                         IIF(MOD(:row_value, 3) = 0, NULL, 'filler'));
                    row_value = row_value + 1;
                END
            END
            """,
            "CREATE TABLE \"viewer_keyless\" (\"position\" BIGINT NOT NULL, \"label\" VARCHAR(80))",
            """
            EXECUTE BLOCK AS
                DECLARE row_value INTEGER = 1;
            BEGIN
                WHILE (row_value <= 205) DO
                BEGIN
                    INSERT INTO "viewer_keyless" ("position", "label")
                    VALUES (:row_value, 'keyless-' || CAST(:row_value AS VARCHAR(10)));
                    row_value = row_value + 1;
                END
            END
            """,
            "CREATE VIEW \"viewer_rows_view\" AS SELECT \"id\", \"code\", \"title\" FROM \"viewer_rows\"",
            "CREATE TABLE \"viewer odd.table\" (\"select\" BIGINT NOT NULL)",
            "INSERT INTO \"viewer odd.table\" (\"select\") VALUES (42)",
        ]);
}
