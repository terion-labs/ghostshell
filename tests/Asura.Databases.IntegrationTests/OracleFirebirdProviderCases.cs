            VALUES
                ('alpha', 'Alpha', -100.00, TRUE, 'one', DEFAULT,
                 TO_TIMESTAMP_TZ('2025-01-01 00:00:00 +00:00', 'YYYY-MM-DD HH24:MI:SS TZH:TZM'),
                 '{"slot":1}', HEXTORAW('0102'))
            """,
            """
            INSERT INTO "viewer_rows"
                ("code", "title", "score", "enabled", "note", "status", "created_at", "payload", "blob_value")
