    private static DatabaseSeed CreateOracleSeed() => new(
        [
            """
            CREATE OR REPLACE FUNCTION "viewer_identity"("value" NUMBER)
            RETURN NUMBER
            IS
            BEGIN
                RETURN "value";
            END;
            """,
            """
            CREATE TABLE "viewer_rows" (
                "id" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "code" VARCHAR2(80 CHAR) NOT NULL UNIQUE,
                "title" VARCHAR2(200 CHAR) NOT NULL,
                "score" NUMBER(12, 2) NOT NULL,
                "enabled" BOOLEAN NOT NULL,
                "note" VARCHAR2(1000 CHAR) NULL,
                "status" VARCHAR2(40 CHAR) DEFAULT 'draft' NOT NULL,
                "created_at" TIMESTAMP WITH TIME ZONE
                    DEFAULT TO_TIMESTAMP_TZ(
                        '2025-01-01 00:00:00 +00:00',
                        'YYYY-MM-DD HH24:MI:SS TZH:TZM') NOT NULL,
                "payload" CLOB DEFAULT '{}' NOT NULL,
                "blob_value" RAW(32) NULL,
                "computed_label" VARCHAR2(281 CHAR)
                    GENERATED ALWAYS AS ("title" || ':' || "code") VIRTUAL,
                CONSTRAINT "ck_viewer_rows_payload_json" CHECK ("payload" IS JSON)
            )
            """,
            "CREATE INDEX \"idx_viewer_rows_score\" ON \"viewer_rows\" (\"score\", \"title\")",
            """
            INSERT INTO "viewer_rows"
