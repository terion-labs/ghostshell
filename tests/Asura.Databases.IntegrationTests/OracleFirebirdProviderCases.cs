                ('beta', 'Beta', 0.00, FALSE, 'Robert''); DROP TABLE viewer_rows;--', 'published',
                 TO_TIMESTAMP_TZ('2025-01-02 00:00:00 +00:00', 'YYYY-MM-DD HH24:MI:SS TZH:TZM'),
                 '{"slot":2}', NULL)
            """,
            """
            INSERT INTO "viewer_rows"
                ("code", "title", "score", "enabled", "note", "created_at", "payload")
            VALUES
                ('literal', 'literal%_!needle', 100.00, TRUE, NULL,
                 TO_TIMESTAMP_TZ('2025-01-03 00:00:00 +00:00', 'YYYY-MM-DD HH24:MI:SS TZH:TZM'),
                 '{"slot":3}')
            """,
            """
            INSERT INTO "viewer_rows"
                ("code", "title", "score", "enabled", "note", "created_at", "payload")
            VALUES
                ('omega-a', 'Omega', 300.00, TRUE, 'four',
                 TO_TIMESTAMP_TZ('2025-01-04 00:00:00 +00:00', 'YYYY-MM-DD HH24:MI:SS TZH:TZM'),
                 '{"slot":4}')
            """,
            """
            INSERT INTO "viewer_rows"
                ("code", "title", "score", "enabled", "note", "created_at", "payload")
